/**
 * Генератор строковых пулов данных. Комбинирует осмысленные фрагменты
 * (основа + уточнение) в уникальные записи, гарантируя отсутствие
 * повторов через Set. Пишет отдельные файлы в src/data/pools/.
 *
 * Движок читает готовые массивы по прежним именам, поэтому расширение
 * данных не затрагивает ни логику, ни синхронизацию.
 */
import fs from 'fs';

/** Комбинирует основы с уточнениями, обрезает до limit, гарантирует уникальность */
function build(bases, qualifiers, { limit, keepPlain = true } = {}) {
  const seen = new Set();
  const out = [];
  // Сначала «чистые» основы — они самые естественные
  if (keepPlain) {
    for (const b of bases) {
      if (!seen.has(b)) { seen.add(b); out.push(b); }
    }
  }
  // Затем основа + уточнение
  for (const q of qualifiers) {
    for (const b of bases) {
      const entry = `${b}${q}`;
      if (!seen.has(entry)) { seen.add(entry); out.push(entry); }
      if (out.length >= limit) return out.slice(0, limit);
    }
  }
  return out.slice(0, limit);
}

function writePool(file, name, comment, arr) {
  const body = arr.map((s) => `  ${JSON.stringify(s)}`).join(',\n');
  const content = `/** ${comment} (${arr.length} записей, сгенерировано) */\nexport const ${name} = [\n${body}\n];\n`;
  fs.writeFileSync(`src/data/pools/${file}`, content);
  console.log(name.padEnd(12), arr.length);
}

