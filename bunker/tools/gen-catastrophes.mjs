const REGIONS = ['над западным полушарием', 'по всему континенту', 'в северных широтах', 'вдоль экватора', 'на обжитых территориях', 'повсеместно', 'в промышленных зонах', 'над океанами и сушей'];
const SPANS = ['за считанные дни', 'в течение недели', 'меньше чем за месяц', 'за один сезон', 'почти мгновенно', 'на протяжении года'];
const NUMS = ['восемь', 'десять', 'двенадцать', 'пятнадцать', 'двадцать', 'тридцать', 'сорок'];
const UNITS = ['лет', 'месяцев', 'зим', 'долгих лет'];

function translit(s) {
  const map = {а:'a',б:'b',в:'v',г:'g',д:'d',е:'e',ё:'e',ж:'zh',з:'z',и:'i',й:'y',к:'k',л:'l',м:'m',н:'n',о:'o',п:'p',р:'r',с:'s',т:'t',у:'u',ф:'f',х:'h',ц:'c',ч:'ch',ш:'sh',щ:'sch',ъ:'',ы:'y',ь:'',э:'e',ю:'yu',я:'ya',' ':'_'};
  return s.toLowerCase().split('').map(c => map[c] ?? '').join('').replace(/_+/g,'_').replace(/[^a-z_]/g,'');
}

const out = [];
const seenNames = new Set();
const seenText = new Set();
let idc = 0;

// Для каждого семейства перебираем комбинации причин × эффектов
for (const fam of FAMILIES) {
  for (let ci = 0; ci < fam.causes.length; ci++) {
    for (let ei = 0; ei < fam.effects.length; ei++) {
      const cause = fam.causes[ci];
      const effect = fam.effects[ei];
      const region = REGIONS[(ci * 3 + ei) % REGIONS.length];
      const span = SPANS[(ci + ei * 2) % SPANS.length];
      const num = NUMS[(ci * 2 + ei) % NUMS.length];
      const unit = UNITS[(ei) % UNITS.length];
      const valued = fam.valued[(ci + ei) % fam.valued.length];

      // Имя: базовое для первой комбинации, вариации дальше
      let name = fam.key;
      if (ci > 0 || ei > 0) {
        const suffixes = ['', ': последствия', ': вторая волна', ': коллапс', ': необратимо', ': чёрный сценарий', ': точка невозврата'];
        name = fam.key + suffixes[(ci * fam.effects.length + ei) % suffixes.length];
      }
      if (seenNames.has(name)) name = `${fam.key} — сценарий ${ci + 1}.${ei + 1}`;
      seenNames.add(name);

      const capCause = cause.charAt(0).toUpperCase() + cause.slice(1);
      const text = `${capCause} ${region}, ${span}: ${effect}. Поверхность останется опасной ещё ${num} ${unit}.`;
      if (seenText.has(text)) continue;
      seenText.add(text);

      const survivors = `Снаружи выжить нельзя. Ценны те, кто разбирается в ${valued}.`;

      out.push({ id: `${translit(fam.key)}_${++idc}`, name, text, survivors });
    }
  }
}

// Записываем файл
const body = out.map(c =>
  `  { id: ${JSON.stringify(c.id)}, name: ${JSON.stringify(c.name)},\n` +
  `    text: ${JSON.stringify(c.text)},\n` +
  `    survivors: ${JSON.stringify(c.survivors)} }`
).join(',\n');

const file = `/**
 * catastrophes.js — база сценариев конца света (сгенерирована).
 * ${out.length} уникальных катастроф. Формат записи неизменен:
 * { id, name, text, survivors } — движок читает его как раньше.
 */

export const CATASTROPHES = [
${body}
];

/** Быстрый доступ по идентификатору */
export const CATASTROPHE_BY_ID = Object.fromEntries(
  CATASTROPHES.map((item) => [item.id, item])
);
`;

fs.writeFileSync('src/data/catastrophes.js', file);
console.log('катастроф сгенерировано:', out.length);
